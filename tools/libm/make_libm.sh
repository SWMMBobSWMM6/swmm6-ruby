#!/bin/bash
# make_libm.sh GLIBC_SRC [WORKDIR] [--all]
# Regenerate the TypeScript, Java and Go ports of glibc 2.39's math routines for the SWMM6 ports from glibc's source:
#   1. build_glibm.sh   compile the routines as glibc's x86-64 build compiles the variants it selects on a processor
#                       with FMA and AVX2, and dump GCC's optimized GIMPLE (the objects are only compiled, never run)
#   2. extract_tables.py copy the constant tables out of the object files (objdump/objcopy; nothing is run)
#   3. gim2x.py         translate the GIMPLE
# Set 2 (always): cbrt, hypot, atan2, cosh, sinh, tanh, log2, expm1, log1p ->
#   go/glibm/glibm2.go, java/src/cpp/Glibm2.java, ts/src/cpp/libm/glibm2.ts (+ the glibm2 runtimes, copied).
# Set 1 (with --all): exp, log, pow, sin, cos, tan, asin, acos, atan, log10 -> go/glibm/glibm.go,
#   java/src/cpp/Glibm.java, ts/src/cpp/libm/glibm.ts. The committed set-1 files are the SWMM5 ports' (generated by
#   swmm5-ports/tools/libm) with their package and import lines changed; this pipeline regenerates the same code
#   (checked: identical apart from those header lines).
# GLIBC_SRC is a checkout of glibc 2.39; the one used was release/2.39/master at ce65d944e38a. WORKDIR (default
# build/glibm) holds the objects and dumps, about 0.5 MB. Then run tools/libm/test/run_tests.sh.
# Written by Claude (Anthropic); see AI-USE.md.
set -e
HERE=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd "$HERE/../.." && pwd)
GL=$(readlink -f "$1"); W=${2:-$ROOT/build/glibm}; ALL=${3:-}
[ "$2" = --all ] && { W=$ROOT/build/glibm; ALL=--all; }
mkdir -p "$W"
"$HERE/build_glibm.sh" "$GL" "$W"
python3 "$HERE/extract_tables.py" "$W" "$W/tables.json"
G=$W/gimple
LG="Derived from the GNU C Library (glibc) 2.39 and so, like glibc's libm, licensed under the GNU Lesser General Public License, version 2.1 or later (LGPL-2.1-or-later)."
WB="Written by Claude (Anthropic) for the SWMM6 ports; see AI-USE.md."

# ---- set 2
D2="$G/s_expm1.c.254t.optimized $G/e_sinh.c.254t.optimized $G/e_cosh.c.254t.optimized $G/s_tanh.c.254t.optimized
    $G/s_log1p.c.254t.optimized $G/e_log2.c.254t.optimized $G/e_atan2.c.254t.optimized $G/s_cbrt.c.254t.optimized
    $G/e_hypot.c.254t.optimized"
H2="Set 2: atan2, log2, sinh, tanh, expm1 and log1p from glibc's FMA variants (sysdeps/x86_64/fpu/multiarch, -mfma -mavx2);
cosh, cbrt and hypot generic. sinh and cosh call set 1's exp (glibm). The public functions at the end pin down NaN results."
T2="--tables $W/tables.json --table-prefix T2_"
# TypeScript and Java: the translations are <name>_t; the public <name> wrappers come from gim2x.py (WRAPPERS_*)
N2="--name my_expm1=expm1_t --name my_sinh=sinh_t --name my_cosh=cosh_t --name my_tanh=tanh_t --name my_log1p=log1p_t
    --name my_log2=log2_t --name my_atan2=atan2_t --name my_cbrt=cbrt_t --name my_hypot=hypot_t"
hdr() { local IFS=$'\n'; for l in $H2 "$LG" "$WB"; do printf -- '--header\n%s\n' "$l"; done; }
mapfile -t HA < <(hdr)
python3 "$HERE/gim2x.py" ts "$ROOT/ts/src/cpp/libm/glibm2.ts" $D2 $T2 $N2 --name my_exp_fma=G.exp \
    --rt ./glibm2_rt.js --import 'import * as G from "./glibm.js";' "${HA[@]}"
python3 "$HERE/gim2x.py" java "$ROOT/java/src/cpp/Glibm2.java" $D2 $T2 $N2 --name my_exp_fma=Glibm.exp \
    --package cpp --rt Glibm2Rt "${HA[@]}"
# Go: exported names, except atan2 and hypot, whose wrappers (Atan2, Hypot) come from gim2x.py
python3 "$HERE/gim2x.py" go "$ROOT/go/glibm/glibm2.go" $D2 $T2 --name my_exp_fma=Exp --name my_expm1=Expm1 \
    --name my_sinh=Sinh --name my_cosh=Cosh --name my_tanh=Tanh --name my_log1p=Log1p --name my_log2=Log2 \
    --name my_atan2=atan2_t --name my_cbrt=Cbrt --name my_hypot=hypot_t "${HA[@]}"
cp "$HERE/glibm2_rt.ts" "$ROOT/ts/src/cpp/libm/glibm2_rt.ts"
cp "$HERE/Glibm2Rt.java" "$ROOT/java/src/cpp/Glibm2Rt.java"
cp "$HERE/glibm2_rt.go" "$ROOT/go/glibm/glibm2_rt.go"
gofmt -w "$ROOT/go/glibm/glibm2.go" "$ROOT/go/glibm/glibm2_rt.go"
echo "wrote set 2: go/glibm/glibm2.go, java/src/cpp/Glibm2.java, ts/src/cpp/libm/glibm2.ts"

# ---- set 1 (only with --all)
[ "$ALL" = --all ] || exit 0
DUMPS="$G/e_exp.c.254t.optimized $G/e_log.c.254t.optimized $G/e_pow.c.254t.optimized $G/s_sin.c.254t.optimized
       $G/s_tan.c.254t.optimized $G/e_asin.c.254t.optimized $G/s_atan.c.254t.optimized $G/e_log10.c.254t.optimized"
NAMES="--name my_exp_fma=exp --name my_log=log --name my_sin=sin --name my_cos=cos
       --name my_tan=tan --name my_asin=ieee754_asin --name my_acos=ieee754_acos --name my_atan=atan
       --name my_log10=ieee754_log10"
# TypeScript calls the translation pow_exact and puts a hand-written fast path, pow, in front of it;
# Java calls the translation pow directly
python3 "$HERE/gim2x.py" ts "$ROOT/ts/src/cpp/libm/glibm.ts" $DUMPS --tables "$W/tables.json" $NAMES --name my_pow=pow_exact \
    --rt ./glibm_rt.js
python3 "$HERE/gim2x.py" java "$ROOT/java/src/cpp/Glibm.java" $DUMPS --tables "$W/tables.json" $NAMES --name my_pow=pow --package cpp
# Go exports capitalised names; log10, asin and acos are wrapped by hand-written SVID wrappers (Log10, Asin, Acos)
python3 "$HERE/gim2x.py" go "$ROOT/go/glibm/glibm.go" $DUMPS --tables "$W/tables.json" --name my_exp_fma=Exp --name my_log=Log \
    --name my_pow=Pow --name my_sin=Sin --name my_cos=Cos --name my_tan=Tan --name my_asin=ieee754_asin \
    --name my_acos=ieee754_acos --name my_atan=Atan --name my_log10=ieee754_log10
cp "$HERE/glibm_rt.ts" "$ROOT/ts/src/cpp/libm/glibm_rt.ts"
cp "$HERE/GlibmRt.java" "$ROOT/java/src/cpp/GlibmRt.java"
cp "$HERE/glibm_rt.go" "$ROOT/go/glibm/glibm_rt.go"
gofmt -w "$ROOT/go/glibm"
echo "wrote set 1: go/glibm/glibm.go, java/src/cpp/Glibm.java, ts/src/cpp/libm/glibm.ts"
