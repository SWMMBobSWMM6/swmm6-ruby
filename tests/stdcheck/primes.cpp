// primes.cpp - print libstdc++'s std::__detail::__prime_list (the table its hash tables size themselves from)
// as a C# array, for cs/runtime/PrimeList.cs. Written by Claude (Anthropic); see AI-USE.md.
#include <cstdio>
namespace std { namespace __detail { extern const unsigned long __prime_list[]; } }
int main() {
    // the table ends with a sentinel; libstdc++'s 64-bit table has 256 + 1 entries plus the sentinel
    std::printf("// Generated by tests/stdcheck/primes.cpp from the system libstdc++. Do not edit.\n");
    std::printf("namespace Cpp { public static class PrimeList { public static readonly ulong[] P = {\n");
    int n = 0;
    for (int i = 0; i < 1000; i++) {
        unsigned long p = std::__detail::__prime_list[i];
        std::printf("%luUL,%s", p, (i % 8 == 7) ? "\n" : " ");
        n++;
        if (p == 18446744073709551557UL) break;   // the largest 64-bit prime ends the table
    }
    std::printf("}; } }\n// %d entries\n", n);
}
